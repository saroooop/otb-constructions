import type { Metadata, Viewport } from 'next';
import { Inter, Archivo } from 'next/font/google';
import './globals.css';
import Nav from '@/components/Nav';
import Footer from '@/components/Footer';
import ServiceWorker from '@/components/ServiceWorker';
import CookieBanner from '@/components/CookieBanner';
import Analytics from '@/components/Analytics';
import { brand, siteUrl } from '@/lib/brand';

// Body — Inter's tall x-height holds up through the long technical
// copy a contractor site carries on its sector and project pages.
const fontSans = Inter({
  variable: '--font-sans',
  subsets: ['latin'],
  weight: ['400', '500', '600', '700'],
});

// Headings — Archivo is a tight industrial grotesque. It gives the
// uppercase, engineered feel the UK tier-one contractors use without
// tipping into the soft geometric look of a tech brand.
const fontHeading = Archivo({
  variable: '--font-heading',
  subsets: ['latin'],
  weight: ['500', '600', '700', '800'],
});

export const metadata: Metadata = {
  // Resolved at build time from `siteUrl`, so canonicals and Open Graph URLs
  // point at the host actually serving the site. Hardcoding lkmd.co.za here
  // published canonicals to a domain that does not resolve yet.
  metadataBase: new URL(siteUrl),
  // No `template` here. The brief gives the exact title tag for every page
  // and says to publish it as written; a template appended the brand a
  // second time, so each page now supplies its own title in full.
  title: `${brand.full} | ${brand.tagline}`,
  description:
    'LKMD Construction plans, designs and builds schools, housing, public buildings, industrial facilities and civil infrastructure for clients across South Africa.',
  keywords: [
    'construction company South Africa',
    'building contractor Gauteng',
    'civil engineering contractor',
    'school construction South Africa',
    'housing construction contractor',
    'refurbishment contractor',
    'construction management South Africa',
    'design and construct contractor',
    'property development support',
    'LKMD Construction',
  ],
  openGraph: {
    type: 'website',
    siteName: brand.full,
    title: `${brand.full} | ${brand.tagline}`,
    // The share card carried the old OTB positioning — "Southern Africa and
    // the UK", mining-led — which contradicts both the brief and the page
    // description beside it. It now repeats the approved description, so a
    // shared link says the same thing as the page it opens.
    description:
      'LKMD Construction plans, designs and builds schools, housing, public buildings, industrial facilities and civil infrastructure for clients across South Africa.',
    images: ['/lkmd-poster.jpg'],
  },
  robots: { index: true, follow: true },

  // PWA. The manifest itself is generated by app/manifest.ts and linked
  // automatically, so only the icon set and the iOS hints belong here.
  applicationName: brand.full,
  appleWebApp: {
    capable: true,
    title: brand.name,
    // 'default' keeps the status bar legible over the navy hero; 'translucent'
    // would let the film run under it and swallow the clock.
    statusBarStyle: 'default',
  },
  icons: {
    icon: [
      { url: '/icons/favicon-32.png', sizes: '32x32', type: 'image/png' },
      { url: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    ],
    apple: [{ url: '/apple-touch-icon.png', sizes: '180x180', type: 'image/png' }],
  },
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  // The hero runs full-bleed, so let it reach into the safe areas on a
  // notched phone rather than leaving navy bars top and bottom.
  viewportFit: 'cover',
  themeColor: brand.color.navy900,
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en-GB" className={`${fontSans.variable} ${fontHeading.variable}`}>
      <head>
        {/* Scroll reveal is a JS effect. Without JS the page must still be
            readable, so neutralise the pre-reveal state entirely. */}
        <noscript>
          <style>{'.reveal{opacity:1!important;transform:none!important}'}</style>
        </noscript>
      </head>
      <body>
        <a
          href="#main"
          style={{
            position: 'absolute', left: -9999, top: 0, zIndex: 999,
            background: '#fff', padding: '12px 20px',
          }}
        >
          Skip to content
        </a>
        <Nav />
        <main id="main">{children}</main>
        <Footer />
        <CookieBanner />
        <Analytics />
        <ServiceWorker />
      </body>
    </html>
  );
}
